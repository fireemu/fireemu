fn span_of(duration: &CalendarDuration) -> Span {
    let n = |v: u64| i64::try_from(v).unwrap();
    let span = Span::new()
        .try_years(n(duration.years))
        .and_then(|s| s.try_months(n(duration.months)))
        .and_then(|s| s.try_weeks(n(duration.weeks)))
        .and_then(|s| s.try_days(n(duration.days)))
        .and_then(|s| s.try_hours(n(duration.hours)))
        .and_then(|s| s.try_minutes(n(duration.minutes)))
        .and_then(|s| s.try_seconds(n(duration.seconds)))
        .unwrap();
    if duration.negative {
        span.negate()
    } else {
        span
    }
}

fn civil(year: i16, month: i8, day: i8, nanos_of_day: i64) -> DateTime {
    let seconds = nanos_of_day / 1_000_000_000;
    DateTime::new(
        year,
        month,
        day,
        i8::try_from(seconds / 3_600).unwrap(),
        i8::try_from(seconds / 60 % 60).unwrap(),
        i8::try_from(seconds % 60).unwrap(),
        i32::try_from(nanos_of_day % 1_000_000_000).unwrap(),
    )
    .unwrap()
}

const END_OF_DAY: i64 = 86_400 * 1_000_000_000 - 1_000;

/// The move as jiff computes it: calendar part on civil time, compatible resolution, then
/// exact time; then the anchor on the civil date, compatible resolution again.
fn oracle(
    start: LogicalInstant,
    tz: &TimeZone,
    duration: Option<&CalendarDuration>,
    anchor: Option<Anchor>,
) -> LogicalInstant {
    let mut zoned = Timestamp::from_nanosecond(start.as_nanos())
        .unwrap()
        .to_zoned_datetime(tz.clone());
    if let Some(duration) = duration {
        zoned = zoned.checked_add(span_of(duration)).unwrap();
    }
    if let Some(anchor) = anchor {
        let date = zoned.datetime().date();
        let (y, m, d) = (date.year(), date.month(), date.day());
        let target = match anchor {
            Anchor::StartOfDay => civil(y, m, d, 0),
            Anchor::EndOfDay => civil(y, m, d, END_OF_DAY),
            Anchor::StartOfMonth => civil(y, m, 1, 0),
            Anchor::EndOfMonth => {
                let last = date.last_of_month();
                civil(y, m, last.day(), END_OF_DAY)
            }
            Anchor::StartOfNextMonth => {
                let next = date
                    .first_of_month()
                    .checked_add(Span::new().months(1))
                    .unwrap();
                civil(next.year(), next.month(), 1, 0)
            }
            Anchor::StartOfYear => civil(y, 1, 1, 0),
            Anchor::EndOfYear => civil(y, 12, 31, END_OF_DAY),
        };
        zoned = target.to_zoned_datetime(tz.clone()).unwrap();
    }
    LogicalInstant::from_nanos(zoned.timestamp().as_nanosecond())
}

fn row_zone(zone: &str) -> &'static str {
    match zone {
        "utc" => "UTC",
        "fixedOffset" => "Asia/Kolkata",
        "dstZone" => "America/New_York",
        // The configured default is chosen by the control API; here it is one more DST zone.
        "configDefault" => "Europe/Paris",
        other => panic!("unknown zone kind {other}"),
    }
}

/// Local start wall time: the day-of-month edge, or one day before a 2025 transition.
fn row_start(tz: &TimeZone, day_edge: &str, dst_edge: &str, zone_name: &str) -> LogicalInstant {
    let (y, m, d, h, mi) = match (dst_edge, zone_name) {
        ("gap", "America/New_York") => (2025, 3, 8, 2, 30),
        ("overlap", "America/New_York") => (2025, 11, 1, 1, 30),
        ("gap", _) => (2025, 3, 29, 2, 30),
        ("overlap", _) => (2025, 10, 25, 2, 30),
        _ => match day_edge {
            "d28" => (2025, 1, 28, 10, 30),
            "d29" => (2025, 1, 29, 10, 30),
            "d30" => (2025, 1, 30, 10, 30),
            "d31" => (2025, 1, 31, 10, 30),
            "leapFeb29" => (2024, 2, 29, 10, 30),
            "mid" => (2025, 6, 15, 10, 30),
            other => panic!("unknown day edge {other}"),
        },
    };
    let dt = DateTime::new(y, m, d, h, mi, 0, 250_000_000).unwrap();
    LogicalInstant::from_nanos(
        dt.to_zoned_datetime(tz.clone())
            .unwrap()
            .timestamp()
            .as_nanosecond(),
    )
}

fn row_duration(units: &str, sign: &str) -> Option<CalendarDuration> {
    let body = match (units, sign) {
        ("none", _) => return None,
        ("clockOnly", "zero") => "PT0S",
        (_, "zero") => "P0D",
        ("years", _) => "P1Y",
        ("months", _) => "P1M",
        ("yearsMonths", _) => "P1Y1M",
        ("weeksDays", _) => "P1W2D",
        ("clockOnly", _) => "PT25H30M15S",
        ("mixed", _) => "P1Y2M3W4DT5H6M7S",
        other => panic!("unknown units {other:?}"),
    };
    let text = if sign == "negative" {
        format!("-{body}")
    } else {
        body.to_owned()
    };
    Some(CalendarDuration::parse(&text).unwrap())
}

#[test]
fn pict_rows_match_the_jiff_oracle() {
    assert_eq!(ROWS.len(), 80);
    for (index, row) in ROWS.iter().enumerate() {
        let f: Vec<&str> = row.split(' ').collect();
        let [op, units, sign, anchor, zone, day_edge, dst_edge, allow] = f[..] else {
            panic!("row {index}: {row}");
        };
        let zone_name = row_zone(zone);
        let tz = iana(zone_name).unwrap();
        let rules = calendar_zone(zone_name).unwrap();
        let start = row_start(&tz, day_edge, dst_edge, zone_name);
        let duration = row_duration(units, sign);
        let anchor = (anchor != "none").then(|| Anchor::parse(anchor).unwrap());
        let got = move_instant(start, &*rules, duration.as_ref(), anchor).unwrap();
        let want = oracle(start, &tz, duration.as_ref(), anchor);
        assert_eq!(got, want, "row {}: {row}", index + 1);
        let kind = match op {
            "advanceDuration" => MoveKind::Advance,
            "setTo" | "setToWithDuration" => MoveKind::Set,
            "advanceToTo" | "advanceToWithDuration" => MoveKind::AdvanceTo,
            other => panic!("unknown op {other}"),
        };
        let allow = allow == "true";
        // The documented rule: forward always; earlier only by advance or set with allowBackwards.
        let expected = if want >= start {
            MoveDecision::Forward
        } else if allow && op != "advanceToTo" && op != "advanceToWithDuration" {
            MoveDecision::Rewind
        } else {
            MoveDecision::RefuseBackwards
        };
        assert_eq!(
            decide(kind, allow, start, got),
            expected,
            "row {}: {row}",
            index + 1
        );
    }
}

#[test]
fn the_rows_reach_gaps_overlaps_and_rewinds() {
    // The table is only useful if its concrete cases exercise the hard paths.
    let mut gaps = 0;
    let mut rewinds = 0;
    for row in ROWS {
        let f: Vec<&str> = row.split(' ').collect();
        let zone_name = row_zone(f[4]);
        let tz = iana(zone_name).unwrap();
        let start = row_start(&tz, f[5], f[6], zone_name);
        let duration = row_duration(f[1], f[2]);
        let anchor = (f[3] != "none").then(|| Anchor::parse(f[3]).unwrap());
        let result = oracle(start, &tz, duration.as_ref(), anchor);
        rewinds += usize::from(result < start);
        if f[6] == "gap" && f[1] == "weeksDays" && f[2] == "positive" {
            gaps += 1;
        }
    }
    assert!(gaps >= 1, "a calendar step into a gap");
    assert!(rewinds >= 10, "rewinds: {rewinds}");
}

#[test]
fn new_york_gap_and_overlap_follow_the_stated_rules() {
    let zone = calendar_zone("America/New_York").unwrap();
    let at = |s: &str| LogicalInstant::parse_rfc3339(s).unwrap();
    let day = CalendarDuration::parse("P1D").unwrap();
    // 2025-03-08 02:30 EST + P1D: 02:30 does not exist on Mar 9; the later instant, 03:30 EDT.
    assert_eq!(
        move_instant(at("2025-03-08T07:30:00Z"), &*zone, Some(&day), None).unwrap(),
        at("2025-03-09T07:30:00Z")
    );
    // 2025-11-01 01:30 EDT + P1D: 01:30 happens twice on Nov 2; the earlier, EDT.
    assert_eq!(
        move_instant(at("2025-11-01T05:30:00Z"), &*zone, Some(&day), None).unwrap(),
        at("2025-11-02T05:30:00Z")
    );
}

#[test]
fn samoa_skipped_a_whole_day_in_2011() {
    // Pacific/Apia jumped from 2011-12-29 23:59:59 -10:00 to 2011-12-31 00:00 +14:00.
    let zone = calendar_zone("Pacific/Apia").unwrap();
    let tz = iana("Pacific/Apia").unwrap();
    let at = |s: &str| LogicalInstant::parse_rfc3339(s).unwrap();
    let start = at("2011-12-29T22:00:00Z"); // 2011-12-29 12:00 local
    let day = CalendarDuration::parse("P1D").unwrap();
    let got = move_instant(start, &*zone, Some(&day), None).unwrap();
    assert_eq!(got, oracle(start, &tz, Some(&day), None));
    // Dec 30 12:00 does not exist: the offset before the gap (-10:00) gives 22:00Z on Dec 30,
    // which reads Dec 31 12:00 local.
    assert_eq!(got, at("2011-12-30T22:00:00Z"));
}

#[test]
fn unknown_and_case_folded_zone_names_are_refused() {
    assert!(calendar_zone("Mars/Olympus").is_err());
    assert!(calendar_zone("america/new_york").is_err());
    assert!(calendar_zone("Factory").is_err());
    assert!(calendar_zone("UTC").is_ok());
}

