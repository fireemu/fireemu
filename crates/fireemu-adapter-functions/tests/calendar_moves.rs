//! Calendar moves of the virtual clock against an independent oracle: jiff's own civil
//! arithmetic and its "compatible" disambiguation, over IANA zones from the bundled database.
//!
//! The core (`fireemu_core_session::calendar`) does the arithmetic itself and asks the zone
//! only for offsets; jiff computes the same move with `DateTime + Span`, `to_zoned_datetime`
//! and timestamp arithmetic. A pairwise (PICT) table covers the request axes, and a property
//! covers random instants, durations and anchors in zones with unusual transitions.

