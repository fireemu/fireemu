fn any_duration() -> impl Strategy<Value = CalendarDuration> {
    (
        any::<bool>(),
        0u64..30,
        0u64..40,
        0u64..60,
        0u64..400,
        0u64..200,
        0u64..2_000,
        0u64..200_000,
    )
        .prop_map(
            |(negative, years, months, weeks, days, hours, minutes, seconds)| {
                let duration = CalendarDuration {
                    negative,
                    years,
                    months,
                    weeks,
                    days,
                    hours,
                    minutes,
                    seconds,
                };
                CalendarDuration {
                    negative: negative && !duration.is_zero(),
                    ..duration
                }
            },
        )
}

proptest! {
    #![proptest_config(ProptestConfig::with_cases(2_000))]

    #[test]
    fn core_moves_agree_with_jiff(
        zone in proptest::sample::select(ZONES.to_vec()),
        seconds in -2_208_988_800i64..4_102_444_800,
        nanos in 0i128..1_000_000_000,
        duration in proptest::option::of(any_duration()),
        anchor in proptest::option::of(proptest::sample::select(Anchor::ALL.to_vec())),
    ) {
        let start = LogicalInstant::from_nanos(i128::from(seconds) * 1_000_000_000 + nanos);
        let tz = iana(zone).unwrap();
        let rules = calendar_zone(zone).unwrap();
        let got = move_instant(start, &*rules, duration.as_ref(), anchor).unwrap();
        prop_assert_eq!(got, oracle(start, &tz, duration.as_ref(), anchor), "{} {:?} {:?}", zone, duration.map(|d| d.to_string()), anchor);
    }

    /// Instants within two days of a real transition, where gaps and overlaps live.
    #[test]
    fn core_moves_agree_with_jiff_near_transitions(
        zone in proptest::sample::select(ZONES.to_vec()),
        from in 0i64..4_102_444_800,
        around in -172_800i64..172_800,
        duration in proptest::option::of(any_duration()),
        anchor in proptest::option::of(proptest::sample::select(Anchor::ALL.to_vec())),
    ) {
        let tz = iana(zone).unwrap();
        let rules = calendar_zone(zone).unwrap();
        let next = tz.following(Timestamp::from_second(from).unwrap()).next();
        let transition = next.map_or(from, |t| t.timestamp().as_second());
        let start = LogicalInstant::from_unix_seconds(transition + around);
        let got = move_instant(start, &*rules, duration.as_ref(), anchor).unwrap();
        prop_assert_eq!(got, oracle(start, &tz, duration.as_ref(), anchor), "{} {:?} {:?}", zone, duration.map(|d| d.to_string()), anchor);
    }
}
