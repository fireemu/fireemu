/// The environment `decide` reads, from `(name, value)` pairs.
fn env_of<'a>(pairs: &'a [(&'a str, &'a str)]) -> impl Fn(&str) -> Option<String> + 'a {
    move |name| {
        pairs
            .iter()
            .find(|(key, _)| *key == name)
            .map(|(_, value)| (*value).to_owned())
    }
}

fn strip_ansi(text: &str) -> String {
    let mut out = String::new();
    let mut chars = text.chars();
    while let Some(c) = chars.next() {
        if c == '\x1b' {
            for next in chars.by_ref() {
                if next == 'm' {
                    break;
                }
            }
        } else {
            out.push(c);
        }
    }
    out
}

/// Pairwise rows of the environment matrix (no-color, clicolor-force, force-color, clicolor, term,
/// tty, os), generated by PICT from the model in the coverage ledger; `unset` leaves the
/// variable out of the environment.
const MATRIX: &[(&str, &str, &str, &str, &str, &str, &str)] = &[
    ("unset", "unset", "unset", "unset", "xterm", "yes", "unix"),
    ("unset", "unset", "unset", "unset", "xterm", "no", "unix"),
    ("1", "unset", "1", "unset", "xterm", "yes", "unix"),
    ("unset", "1", "unset", "unset", "dumb", "no", "unix"),
    ("unset", "unset", "unset", "unset", "unset", "yes", "unix"),
    (
        "unset", "unset", "unset", "unset", "unset", "yes", "windows",
    ),
    (
        "unset", "unset", "unset", "unset", "xterm", "yes", "windows",
    ),
    ("unset", "unset", "1", "unset", "unset", "no", "windows"),
    ("unset", "unset", "unset", "0", "xterm", "yes", "unix"),
    ("unset", "0", "0", "unset", "xterm", "yes", "unix"),
    ("empty", "unset", "unset", "unset", "xterm", "yes", "unix"),
    ("1", "unset", "0", "1", "dumb", "no", "windows"),
    ("empty", "unset", "false", "0", "unset", "no", "windows"),
    ("empty", "0", "unset", "1", "dumb", "no", "windows"),
    ("1", "1", "unset", "1", "unset", "yes", "unix"),
    ("empty", "1", "1", "0", "dumb", "yes", "windows"),
    ("unset", "1", "false", "1", "xterm", "yes", "unix"),
    ("1", "0", "1", "0", "unset", "yes", "windows"),
    ("empty", "1", "0", "0", "unset", "yes", "windows"),
    ("1", "0", "false", "unset", "dumb", "no", "unix"),
    ("1", "unset", "1", "1", "dumb", "yes", "unix"),
];

/// The expected answer, from a different shape than `decide`: a rule per environment, first
/// match wins.
fn expected(row: &(&str, &str, &str, &str, &str, &str, &str)) -> bool {
    let (no_color, cli_force, force, cli_color, term, tty, os) = *row;
    if no_color == "1" {
        return false;
    }
    if cli_force == "1" || force == "1" {
        return true;
    }
    if term == "dumb" || cli_color == "0" {
        return false;
    }
    match (tty, os) {
        ("no", _) => false,
        ("yes", "unix") => true,
        ("yes", "windows") => term == "xterm",
        other => unreachable!("{other:?}"),
    }
}

#[test]
fn pairwise_environment_matrix_matches_the_rules() {
    for row in MATRIX {
        let (no_color, cli_force, force, cli_color, term, tty, os) = *row;
        let pairs: Vec<(&str, &str)> = [
            ("NO_COLOR", no_color),
            ("CLICOLOR_FORCE", cli_force),
            ("FORCE_COLOR", force),
            ("CLICOLOR", cli_color),
            ("TERM", term),
        ]
        .into_iter()
        .filter(|(_, value)| *value != "unset")
        .map(|(name, value)| (name, if value == "empty" { "" } else { value }))
        .collect();
        let got = decide(&env_of(&pairs), tty == "yes", os == "windows");
        assert_eq!(got, expected(row), "{row:?}");
    }
}

#[test]
fn a_terminal_with_a_plain_environment_gets_colour() {
    assert!(decide(&env_of(&[]), true, false));
    assert!(decide(&env_of(&[("TERM", "xterm-256color")]), true, false));
}

#[test]
fn a_stream_that_is_not_a_terminal_gets_no_colour() {
    assert!(!decide(&env_of(&[("TERM", "xterm")]), false, false));
    assert!(!decide(&env_of(&[]), false, false));
}

#[test]
fn no_color_wins_over_every_force_variable_and_empty_is_ignored() {
    let forced = [
        ("NO_COLOR", "1"),
        ("CLICOLOR_FORCE", "1"),
        ("FORCE_COLOR", "1"),
    ];
    assert!(!decide(&env_of(&forced), true, false));
    assert!(!decide(&env_of(&[("NO_COLOR", "anything")]), true, false));
    assert!(decide(&env_of(&[("NO_COLOR", "")]), true, false));
}

#[test]
fn force_variables_accept_any_value_but_empty_zero_and_false() {
    for value in ["1", "2", "true", "always", "yes"] {
        assert!(
            decide(&env_of(&[("FORCE_COLOR", value)]), false, false),
            "{value}"
        );
        assert!(
            decide(&env_of(&[("CLICOLOR_FORCE", value)]), false, false),
            "{value}"
        );
    }
    for value in ["", "0", "false", "FALSE"] {
        assert!(
            !decide(&env_of(&[("FORCE_COLOR", value)]), false, false),
            "{value}"
        );
        assert!(
            !decide(&env_of(&[("CLICOLOR_FORCE", value)]), false, false),
            "{value}"
        );
    }
}

#[test]
fn force_beats_a_dumb_terminal_and_clicolor_zero() {
    let dumb = [("TERM", "dumb"), ("CLICOLOR", "0"), ("CLICOLOR_FORCE", "1")];
    assert!(decide(&env_of(&dumb), false, false));
}

#[test]
fn a_dumb_terminal_and_clicolor_zero_turn_colour_off_on_a_terminal() {
    assert!(!decide(&env_of(&[("TERM", "dumb")]), true, false));
    assert!(!decide(&env_of(&[("CLICOLOR", "0")]), true, false));
    assert!(decide(&env_of(&[("CLICOLOR", "1")]), true, false));
}

#[test]
fn windows_needs_a_terminal_that_interprets_ansi_sequences() {
    assert!(!decide(&env_of(&[]), true, true));
    assert!(decide(&env_of(&[("TERM", "xterm")]), true, true));
    assert!(decide(&env_of(&[("ANSICON", "120x30")]), true, true));
    assert!(decide(&env_of(&[("ConEmuANSI", "ON")]), true, true));
    assert!(!decide(&env_of(&[("ConEmuANSI", "OFF")]), true, true));
    assert!(decide(&env_of(&[("CLICOLOR_FORCE", "1")]), true, true));
    assert!(!decide(&env_of(&[("TERM", "xterm")]), false, true));
}

const RESET: &str = "\x1b[0m";

#[test]
fn the_heading_is_bold() {
    assert_eq!(
        paint_line("fireemu up"),
        format!("\x1b[1mfireemu up{RESET}")
    );
    assert_eq!(
        paint_line("fireemu exec"),
        format!("\x1b[1mfireemu exec{RESET}")
    );
}

#[test]
fn error_warning_and_note_prefixes_are_red_yellow_and_dim() {
    assert_eq!(
        paint_line("error: bind failed"),
        format!("\x1b[1;31merror:{RESET} bind failed")
    );
    assert_eq!(
        paint_line("warning: slow"),
        format!("\x1b[1;33mwarning:{RESET} slow")
    );
    assert_eq!(
        paint_line("note: reloaded"),
        format!("\x1b[2mnote:{RESET} reloaded")
    );
    assert_eq!(
        paint_line("  note: indented"),
        format!("  \x1b[2mnote:{RESET} indented")
    );
}

