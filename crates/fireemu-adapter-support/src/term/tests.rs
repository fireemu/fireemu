proptest! {
    #[test]
    fn painting_a_log_line_only_adds_escape_sequences(
        tag in "\\[[a-z:]{1,10}\\]",
        level in "[a-zA-Z]{0,9}",
        id in proptest::option::of("[a-f0-9]{1,8}"),
        message in "[ -~\n]{0,60}",
    ) {
        let plain = id.as_deref().map_or_else(
            || format!("{tag} {level} {message}"),
            |id| format!("{tag} {level} {id} {message}"),
        );
        prop_assert_eq!(strip_ansi(&log_line_always(&tag, &level, id.as_deref(), &message)), plain);
    }

    #[test]
    fn painting_a_tagged_line_only_adds_escape_sequences(
        line in "[ -~]{0,60}",
        level in prop::sample::select(vec![Level::Error, Level::Warn, Level::Info, Level::Debug]),
    ) {
        prop_assert_eq!(strip_ansi(&tagged_line_always(level, &line)), line);
    }

    #[test]
    fn colour_never_depends_on_the_stream_when_forced(
        forced in prop::sample::select(vec!["CLICOLOR_FORCE", "FORCE_COLOR"]),
        tty in any::<bool>(),
        windows in any::<bool>(),
    ) {
        prop_assert!(decide(&env_of(&[(forced, "1")]), tty, windows));
    }

    #[test]
    fn no_color_is_never_overridden(
        value in "[ -~]{1,8}",
        tty in any::<bool>(),
        windows in any::<bool>(),
        force in prop::sample::select(vec!["0", "1", "true"]),
    ) {
        let pairs = [("NO_COLOR", value.as_str()), ("FORCE_COLOR", force), ("CLICOLOR_FORCE", force)];
        prop_assert!(!decide(&env_of(&pairs), tty, windows));
    }
}

/// The three writers of a diagnostic, with the plain text each must give when colour is off and
/// the text it gives when colour is on.
fn writers() -> [(String, String); 3] {
    [
        (
            log_line("[f]", "warning", Some("id"), "m"),
            log_line_always("[f]", "warning", Some("id"), "m"),
        ),
        (raw_line("[f]", "raw"), format!("{} raw", wrap(DIM, "[f]"))),
        (
            tagged_line(Level::Warn, "[f] w"),
            tagged_line_always(Level::Warn, "[f] w"),
        ),
    ]
}

const PLAIN: [&str; 3] = ["[f] warning id m", "[f] raw", "[f] w"];

/// Runs this test in a child process with `env`, so that the process-wide, once-only decision is
/// made from that environment.
fn run_child(env: &[(&str, &str)]) -> std::process::Output {
    let mut command = std::process::Command::new(std::env::current_exe().unwrap());
    command
        .args([
            "--exact",
            "term::tests::the_environment_decides_the_writers_in_a_child_process",
            "--nocapture",
        ])
        .env("FIREEMU_TERM_CHILD", "1")
        .env_remove("NO_COLOR")
        .env_remove("CLICOLOR")
        .env_remove("CLICOLOR_FORCE")
        .env_remove("FORCE_COLOR")
        .env_remove("TERM");
    for (name, value) in env {
        command.env(name, value);
    }
    // Piped, so that the child's stderr is not a terminal whoever runs the tests.
    command.stdin(std::process::Stdio::null()).output().unwrap()
}

#[test]
fn the_environment_decides_the_writers_in_a_child_process() {
    if std::env::var_os("FIREEMU_TERM_CHILD").is_none() {
        let out = run_child(&[("CLICOLOR_FORCE", "1")]);
        assert!(out.status.success(), "{out:?}");
        let out = run_child(&[("CLICOLOR_FORCE", "1"), ("NO_COLOR", "1")]);
        assert!(out.status.success(), "{out:?}");
        let out = run_child(&[]);
        assert!(out.status.success(), "{out:?}");
        return;
    }
    let forced = std::env::var_os("CLICOLOR_FORCE").is_some();
    let off = std::env::var_os("NO_COLOR").is_some();
    let expect_colour = forced && !off;
    assert_eq!(enabled(Stream::Stderr), expect_colour);
    for ((written, painted), plain) in writers().iter().zip(PLAIN) {
        if expect_colour {
            assert_eq!(written, painted);
            assert_ne!(written, plain);
        } else {
            assert_eq!(written, plain);
        }
    }
}
